#!/usr/bin/env python3
"""Point kitty and the live compositor at a Tanjun palette.

Named presets are hand-written: this rewrites their include lines and the
compositor pointer. "From wall" is generated by matugen, which also writes the
compositor strip (see matugen/config*.toml) from the same run.
"""
from __future__ import annotations

import json
import os
import re
import shutil
import signal
import subprocess
import sys
from pathlib import Path

HOME = Path.home()
CONFIG = Path(os.environ.get("XDG_CONFIG_HOME", HOME / ".config"))
STATE = Path(os.environ.get("XDG_STATE_HOME", HOME / ".local/state")) / "tanjun"
CACHE = Path(os.environ.get("XDG_CACHE_HOME", HOME / ".cache")) / "tanjun"
PID_FILE = STATE / "wall.pids"
SLUG = re.compile(r"^[a-z0-9_-]+$")
EXTS = ("png", "jpg", "jpeg", "webp", "bmp", "gif")
VIDEO_EXTS = ("mp4", "webm", "mkv", "mov", "m4v")
MPV_OPTS = "no-audio --loop-file=inf --hwdec=auto --panscan=1.0 --no-osc --osd-level=0 --no-input-default-bindings"


def on_niri() -> bool:
    return bool(os.environ.get("NIRI_SOCKET"))


def is_video(path: Path) -> bool:
    return path.suffix.lower().lstrip(".") in VIDEO_EXTS


def slug(value: str, fallback: str = "monochrome") -> str:
    raw = (value or "").strip().lower()
    if raw == "wall":
        return "wall"
    if SLUG.match(raw):
        return raw
    return fallback


def wall_dirs() -> list[Path]:
    own = STATE / "walls"
    legacy = CONFIG / "hypr/assets/wallpapers"
    out: list[Path] = []
    if own.is_dir():
        out.append(own)
    if legacy.is_dir():
        out.append(legacy)
    return out or [own]


def _load_pids() -> dict:
    try:
        data = json.loads(PID_FILE.read_text(encoding="utf-8"))
        return data if isinstance(data, dict) else {}
    except (OSError, ValueError, TypeError):
        return {}


def _save_pids(data: dict) -> None:
    STATE.mkdir(parents=True, exist_ok=True)
    PID_FILE.write_text(json.dumps(data), encoding="utf-8")


def _kill_pid(key: str, sig: int = signal.SIGTERM) -> None:
    data = _load_pids()
    pid = data.pop(key, None)
    if pid:
        try:
            os.kill(int(pid), sig)
        except (OSError, ValueError, TypeError):
            pass
    _save_pids(data)


def _signal_pid(key: str, sig: int) -> None:
    data = _load_pids()
    pid = data.get(key)
    if not pid:
        return
    try:
        os.kill(int(pid), sig)
    except (OSError, ValueError, TypeError):
        data.pop(key, None)
        _save_pids(data)


def _remember(key: str, pid: int) -> None:
    data = _load_pids()
    data[key] = pid
    _save_pids(data)


def pin_wall(wall: Path) -> None:
    STATE.mkdir(parents=True, exist_ok=True)
    (STATE / "wall").write_text(str(wall) + "\n")


def rewrite_line(path: Path, pattern: str, repl: str) -> bool:
    if not path.is_file():
        return False
    text = path.read_text()
    new, n = re.subn(pattern, repl, text, count=1, flags=re.M)
    if n and new != text:
        path.write_text(new)
        return True
    return False


def current_wall() -> Path | None:
    pin = STATE / "wall"
    if pin.is_file():
        p = Path(pin.read_text().strip()).expanduser()
        if p.is_file():
            return p
    conf = CONFIG / "hypr/hyprpaper.conf"
    if conf.is_file():
        for line in conf.read_text().splitlines():
            m = re.match(r"\s*path\s*=\s*(.+)", line)
            if not m:
                continue
            p = Path(os.path.expanduser(m.group(1).strip()))
            if p.is_file():
                return p
    bg = CONFIG / "background"
    if bg.exists():
        try:
            return bg.resolve()
        except OSError:
            return None
    return None


def find_wall(name: str) -> Path | None:
    name = slug(name, name)
    for folder in wall_dirs():
        if not folder.is_dir():
            continue
        for ext in EXTS:
            p = folder / f"{name}.{ext}"
            if p.is_file():
                return p
        hits = sorted(folder.glob(f"{name}.*"))
        if hits:
            return hits[0]
    return current_wall()


def paint_kitty(kind: str, name: str) -> None:
    kind = slug(kind, "dark")
    name = slug(name, "monochrome")
    conf = CONFIG / "kitty/kitty.conf"
    rewrite_line(
        conf,
        r"include themes/[^/\s]+/[^\s]+\.conf",
        f"include themes/{kind}/{name}.conf",
    )
    subprocess.run(["pkill", "-USR1", "-x", "kitty"], check=False, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)


def paint_hypr(kind: str, name: str) -> None:
    if on_niri():
        paint_niri(kind, name)
        return
    point_theme(slug(kind, "dark"), slug(name, "monochrome"))


def point_theme(kind: str, name: str) -> None:
    """Point Hyprland at a theme table and ask it to re-read.

    niri has no pointer file: its colours go to tanjun-colors.kdl instead.
    """
    lua = CONFIG / "hypr/hyprland/active_theme.lua"
    if lua.is_file():
        lua.write_text(f'return "hyprland.themes.{kind}.{name}"\n')
    subprocess.run(["hyprctl", "reload"], check=False, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)


def paint_niri(kind: str, name: str) -> None:
    """Write the strip of layout niri redraws from the active palette.

    niri has no pointer file like Hyprland's active_theme.lua, so the colours
    land in ~/.config/niri/tanjun-colors.kdl, which the clone's layout.kdl
    includes after its own defaults. Repeated nodes merge, so this block wins.
    """
    preset = preset_colors(kind, name)
    if preset is None:
        return
    bg = parse_rgb(preset.get("bg", "#1b1b1f"))
    surf = parse_rgb(preset.get("surface", "#252525"))
    acc = parse_rgb(preset.get("accent", "#e0e0e0"))
    (CONFIG / "niri/tanjun-colors.kdl").write_text(
        "// Generated by tanjun-paint.py. Edit the Tanjun theme instead.\n"
        "layout {\n"
        f'    background-color "{hexc(bg)}"\n'
        "    border {\n"
        "        // Included files need `on`: without it an included border\n"
        "        // section changes nothing.\n"
        "        on\n"
        f'        active-color "{hexc(acc)}"\n'
        f'        inactive-color "{hexc(surf)}"\n'
        "    }\n"
        "}\n"
    )


def preset_colors(kind: str, name: str) -> dict | None:
    """The palette for a named preset, read from the shipped Hyprland theme.

    The clone keeps one Lua table per preset, so the KDL side reads the same
    numbers rather than carrying a second copy that can drift.
    """
    kind = slug(kind, "dark")
    name = slug(name, "monochrome")
    theme = Path(__file__).resolve().parent.parent.parent / "compositors" / "hyprland" / "themes" / kind / f"{name}.lua"
    try:
        text = theme.read_text(encoding="utf-8")
    except OSError:
        return None

    def slot(key: str, fallback: str) -> str:
        m = re.search(rf'^\s*{key} = "rgb\(([0-9a-fA-F]{{6}})\)"', text, re.M)
        return f"#{m.group(1)}" if m else fallback

    return {
        "bg": slot("base", "#1b1b1f"),
        "surface": slot("surface0", "#252525"),
        "accent": slot("border_primary", "#e0e0e0"),
    }


def parse_rgb(h: str) -> tuple[int, int, int]:
    h = str(h).lstrip("#")
    if len(h) == 3:
        h = "".join(c * 2 for c in h)
    if len(h) < 6:
        return (30, 30, 30)
    return int(h[0:2], 16), int(h[2:4], 16), int(h[4:6], 16)


def paint_lock(kind: str, name: str) -> None:
    if on_niri():
        return
    rewrite_line(
        CONFIG / "hypr/hyprlock.conf",
        r"source = \$HOME/\.config/hypr/hyprlockThemes/[^/\s]+/[^\s]+\.conf",
        f"source = $HOME/.config/hypr/hyprlockThemes/{kind}/{name}.conf",
    )


def still_of(wall: Path) -> Path:
    if not is_video(wall):
        return wall
    CACHE.mkdir(parents=True, exist_ok=True)
    out = CACHE / "wall-still.jpg"
    if out.is_file() and out.stat().st_mtime >= wall.stat().st_mtime and out.stat().st_size > 0:
        return out
    r = subprocess.run(
        ["ffmpeg", "-y", "-ss", "1", "-i", str(wall), "-frames:v", "1", "-q:v", "3", str(out)],
        check=False,
        stdout=subprocess.DEVNULL,
        stderr=subprocess.DEVNULL,
    )
    if r.returncode == 0 and out.is_file() and out.stat().st_size > 0:
        return out
    return wall


def link_background(path: Path, bg: Path | None = None) -> None:
    target = bg if bg is not None else CONFIG / "background"
    try:
        if target.is_symlink():
            target.unlink()
        elif target.exists():
            return
        target.symlink_to(path)
    except OSError:
        pass


def stop_video() -> None:
    _kill_pid("mpvpaper")


def stop_still() -> None:
    _kill_pid("swaybg")
    _kill_pid("hyprpaper")


def start_video(wall: Path) -> None:
    if shutil.which("mpvpaper") is None:
        return
    stop_still()
    stop_video()
    p = subprocess.Popen(
        ["mpvpaper", "-o", MPV_OPTS, "*", str(wall)],
        stdout=subprocess.DEVNULL,
        stderr=subprocess.DEVNULL,
        start_new_session=True,
    )
    _remember("mpvpaper", p.pid)


def write_hyprpaper(wall: Path) -> None:
    home = str(HOME)
    raw = str(wall)
    shown = f"~{raw[len(home):]}" if raw.startswith(home + os.sep) else raw
    conf = CONFIG / "hypr/hyprpaper.conf"
    if not conf.is_file():
        return
    lines = conf.read_text().splitlines(True)
    out = []
    in_block = False
    for line in lines:
        if re.match(r"^preload\s*=", line):
            line = f"preload = {shown}\n"
        if re.match(r"^wallpaper\s*\{", line):
            in_block = True
        elif in_block and re.match(r"^\s*path\s*=", line):
            indent = re.match(r"^(\s*)", line).group(1)
            line = f"{indent}path = {shown}\n"
        if in_block and line.strip() == "}":
            in_block = False
        out.append(line)
    conf.write_text("".join(out))


def start_still(wall: Path) -> None:
    stop_video()
    if on_niri():
        _kill_pid("swaybg")
        # niri draws no wallpaper itself; swaybg is the usual daemon and the nix
        # modules install it. Missing it must not cost the palette, so skip.
        if shutil.which("swaybg") is None:
            print("tanjun-paint: swaybg not found, wallpaper not drawn", file=sys.stderr)
            return
        p = subprocess.Popen(
            ["swaybg", "-i", str(wall), "-m", "fill"],
            stdout=subprocess.DEVNULL,
            stderr=subprocess.DEVNULL,
            start_new_session=True,
        )
        _remember("swaybg", p.pid)
        return
    if shutil.which("hyprpaper") is None:
        print("tanjun-paint: hyprpaper not found, wallpaper not drawn", file=sys.stderr)
        return
    write_hyprpaper(wall)
    conf = CONFIG / "hypr/hyprpaper.conf"
    _kill_pid("hyprpaper")
    cmd = ["hyprpaper"]
    if conf.is_file():
        cmd.extend(["--config", str(conf)])
    p = subprocess.Popen(
        cmd,
        stdout=subprocess.DEVNULL,
        stderr=subprocess.DEVNULL,
        start_new_session=True,
    )
    _remember("hyprpaper", p.pid)


def apply_wall_file(wall: Path) -> Path | None:
    wall = wall.expanduser().resolve()
    if not wall.is_file():
        return None
    pin_wall(wall)
    still = still_of(wall)
    link_background(still)
    if is_video(wall):
        start_video(wall)
    else:
        start_still(wall)
    return wall


def paint_wall(name: str) -> Path | None:
    wall = find_wall(name)
    if wall is None:
        return None
    return apply_wall_file(wall)


def hexc(rgb: tuple[int, int, int]) -> str:
    return "#{:02x}{:02x}{:02x}".format(*rgb)


def fallback_pal(wall: Path, still: Path) -> dict:
    return {
        "kind": "wall",
        "name": "wall",
        "label": "From wall",
        "accent": "#e0e0e0",
        "accentHover": "#f0f0f0",
        "critical": "#ef4444",
        "warning": "#eab308",
        "info": "#808080",
        "good": "#7bc379",
        "fg": "#d4d4d4",
        "fgSub": "#9ca3af",
        "bg": "#1b1b1f",
        "surface": "#252525",
        "surfaceHover": "#2e2e36",
        "wall": str(wall),
        "wallStill": str(still),
    }


MATUGEN_DIR = Path(__file__).resolve().parent.parent.parent / "matugen"


def matugen_palette(still: Path) -> dict | None:
    """Derive the palette from the wallpaper with matugen.

    The compositor picks its config: both write the shell palette, then either
    the Hyprland theme table or niri's tanjun-colors.kdl, so one call colours
    the shell and the compositor from the same numbers. Presets never come
    through here — they are hand-written and matugen does not touch them.
    """
    exe = shutil.which("matugen")
    config = MATUGEN_DIR / ("config-niri.toml" if on_niri() else "config.toml")
    if exe is None or not config.is_file():
        return None
    STATE.mkdir(parents=True, exist_ok=True)
    out = STATE / "palette.json"
    try:
        out.unlink()
    except FileNotFoundError:
        pass
    run = subprocess.run(
        [exe, "image", str(still), "-c", str(config), "-m", "smart", "-t", "scheme-content", "-q"],
        check=False,
        stdout=subprocess.DEVNULL,
        stderr=subprocess.DEVNULL,
    )
    if run.returncode != 0 or not out.is_file():
        return None
    try:
        pal = json.loads(out.read_text(encoding="utf-8"))
    except ValueError:
        return None
    return pal if pal.get("accent") else None


def pal_from(wall: Path) -> dict:
    still = still_of(wall)
    pal = matugen_palette(still) or fallback_pal(wall, still)
    pal["wall"] = str(wall)
    pal["wallStill"] = str(still)
    return pal


def point_wall() -> None:
    """Point the compositor at the wall colours matugen just wrote."""
    if not on_niri():
        point_theme("wall", "wall")


def cmd_sample() -> None:
    wall = current_wall()
    if wall is None:
        print("{}", flush=True)
        return
    pal = pal_from(wall)
    point_wall()
    print(json.dumps(pal), flush=True)


def cmd_set(path: str) -> None:
    wall = apply_wall_file(Path(path))
    if wall is None:
        print("{}", flush=True)
        return
    pal = pal_from(wall)
    point_wall()
    print(json.dumps(pal), flush=True)


def cmd_wall(path: str) -> None:
    wall = apply_wall_file(Path(path))
    if wall is None:
        print("{}", flush=True)
        return
    still = still_of(wall)
    print(json.dumps({"wall": str(wall), "wallStill": str(still)}), flush=True)


def cmd_restore() -> None:
    wall = current_wall()
    if wall is not None:
        apply_wall_file(wall)
        return
    if on_niri():
        bg = CONFIG / "background"
        if bg.exists():
            start_still(bg)
        return
    conf = CONFIG / "hypr/hyprpaper.conf"
    if conf.is_file() and shutil.which("hyprpaper") is not None:
        stop_video()
        p = subprocess.Popen(
            ["hyprpaper", "--config", str(conf)],
            stdout=subprocess.DEVNULL,
            stderr=subprocess.DEVNULL,
            start_new_session=True,
        )
        _remember("hyprpaper", p.pid)


def cmd_paint(kind: str, name: str) -> None:
    kind = slug(kind, "dark")
    name = slug(name, "monochrome")
    paint_kitty(kind, name)
    paint_lock(kind, name)
    # Before paint_wall: that one spawns a wallpaper tool and can fail if the
    # tool is missing, which must not cost the compositor its colours.
    paint_hypr(kind, name)
    wall = paint_wall(name)
    if wall is None:
        print("{}", flush=True)
        return
    still = still_of(wall)
    print(json.dumps({"wall": str(wall), "wallStill": str(still)}), flush=True)


def main() -> None:
    args = sys.argv[1:]
    if not args:
        sys.exit(1)
    if args[0] == "sample":
        cmd_sample()
        return
    if args[0] == "restore":
        cmd_restore()
        return
    if args[0] == "pause":
        _signal_pid("mpvpaper", signal.SIGSTOP)
        return
    if args[0] == "resume":
        _signal_pid("mpvpaper", signal.SIGCONT)
        return
    if args[0] == "set" and len(args) > 1:
        cmd_set(args[1])
        return
    if args[0] == "wall" and len(args) > 1:
        cmd_wall(args[1])
        return
    kind, name = args[0], args[1] if len(args) > 1 else "monochrome"
    if name == "wall" or kind == "wall":
        cmd_sample()
        return
    cmd_paint(kind, name)


if __name__ == "__main__":
    main()
